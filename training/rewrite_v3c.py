"                lengths, batch_off,\n",
"                out_w, out_b, out_ev):\n",
"    B = len(batch_idx)\n",
"    for i in prange(B):\n",
"        idx = batch_idx[i]\n",
"        is_mirror = mirror and (idx >= n)\n",
"        ri = idx - n if is_mirror else idx\n",
"        start = offsets_arr[ri]\n",
"        out_pos = batch_off[i]\n",
"        length = lengths[i]\n",
"        is_black = stm[ri] == 1\n",
