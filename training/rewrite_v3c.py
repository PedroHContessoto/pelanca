"@njit(cache=True)\n",
"def _batch_offsets(offsets_arr, batch_idx, n, mirror):\n",
"    B = len(batch_idx)\n",
"    lengths = np.empty(B, dtype=np.int64)\n",
"    batch_off = np.empty(B, dtype=np.int64)\n",
