"            b = np.int64(b_flat[start + j])\n",
"            if is_mirror:\n",
"                w ^= 7\n",
"                b ^= 7\n",
"            if is_black:\n",
"                w, b = b, w\n",
"            out_w[out_pos + j] = w\n",
"            out_b[out_pos + j] = b\n",
"        ev = evals[ri]\n",
"        if is_black:\n",
"            ev = -ev\n",
"        out_ev[i] = ev\n",
"\n",
"\n",
